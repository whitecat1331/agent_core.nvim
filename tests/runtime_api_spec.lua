---@mod tests.runtime_api_spec Unit tests for the owned runtime config, clipboard, and API.

local h = require("tests.harness")
local Config = require("agent_core.runtime.config")
local Clipboard = require("agent_core.runtime.clipboard")
local Runtime = require("agent_core.runtime")

h.describe("runtime.config", function()
  h.it("merge returns defaults without user options", function()
    local cfg = Config.merge()
    h.equals(25, cfg.session.max_iterations)
    h.equals(true, cfg.ui.indicator)
    h.equals(9, cfg.ui.max_panes)
  end)

  h.it("merge deep-merges user options over defaults", function()
    local cfg = Config.merge({ session = { max_iterations = 5 }, ui = { max_panes = 4 } })
    h.equals(5, cfg.session.max_iterations)
    h.equals(4, cfg.ui.max_panes)
    h.equals(true, cfg.ui.indicator, "unspecified defaults should be preserved")
  end)

  h.it("merge does not mutate the shared defaults", function()
    local _ = Config.merge({ session = { max_iterations = 1 } })
    h.equals(25, Config.defaults.session.max_iterations)
  end)

  h.it("filter_tools drops disabled tools", function()
    local out = Config.filter_tools({ { name = "a" }, { name = "b" } }, { tools = { b = false } })
    h.equals(1, #out)
    h.equals("a", out[1].name)
  end)
end)

h.describe("runtime.clipboard", function()
  h.it("vision_part encodes bytes as a base64 image part", function()
    local part = Clipboard.vision_part("hi", "image/png")
    h.equals("image", part.type)
    h.equals("base64", part.source.type)
    h.equals("image/png", part.source.media_type)
    h.equals("aGk=", part.source.data)
  end)

  h.it("media_type_for maps extensions and defaults to png", function()
    h.equals("image/png", Clipboard.media_type_for("a.png"))
    h.equals("image/jpeg", Clipboard.media_type_for("a.jpg"))
    h.equals("image/webp", Clipboard.media_type_for("a.WEBP"))
    h.equals("image/png", Clipboard.media_type_for("noext"))
  end)

  h.it("image_part reads a file into a vision part", function()
    local dir = vim.fn.tempname()
    vim.fn.mkdir(dir, "p")
    local path = dir .. "/x.png"
    vim.fn.writefile({ "PNGDATA" }, path)
    local part, err = Clipboard.image_part(path)
    h.equals(nil, err)
    h.equals("image", part.type)
    h.equals("image/png", part.source.media_type)
    h.truthy(#part.source.data > 0, "data should be base64-encoded")
    vim.fn.delete(dir, "rf")
  end)

  h.it("image_part errors on a missing file", function()
    local part, err = Clipboard.image_part(vim.fn.tempname() .. "/nope.png")
    h.equals(nil, part)
    h.truthy(err ~= nil, "missing file should error")
  end)
end)

h.describe("runtime api (sessions/submit/model)", function()
  local function reset()
    Runtime._sessions = {}
    Runtime._active = 0
  end

  h.it("create_session tracks and focuses the first session", function()
    reset()
    local s = Runtime.create_session({ provider = "deepseek", model = "m1" })
    h.equals(1, #Runtime.sessions())
    h.equals(s, Runtime.active_session())
    h.equals("deepseek", s.provider)
    h.equals("m1", s.model)
    reset()
  end)

  h.it("get_session and focus_session resolve by id", function()
    reset()
    local s1 = Runtime.create_session({ provider = "deepseek", model = "a" })
    local s2 = Runtime.create_session({ provider = "deepseek", model = "b" })
    h.equals(s1, Runtime.get_session(s1.id))
    h.equals(s2, Runtime.focus_session(s2.id))
    h.equals(s2, Runtime.active_session())
    reset()
  end)

  h.it("model switches the active session provider/model", function()
    reset()
    local s = Runtime.create_session({ provider = "deepseek", model = "m1" })
    local ok, err = Runtime.model("claude", "sonnet")
    h.equals(nil, err)
    h.truthy(ok)
    h.equals("claude", s.provider)
    h.equals("sonnet", s.model)
    reset()
  end)

  h.it("model reports an error without an active session", function()
    reset()
    local ok, err = Runtime.model("claude", "sonnet")
    h.equals(false, ok)
    h.truthy(err ~= nil, "should error with no session")
    reset()
  end)
end)
