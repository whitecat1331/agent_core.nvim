---@mod tests.mentions_spec Unit tests for agent_core.mentions tokenizer.

local h = require("tests.harness")
local Mentions = require("agent_core.mentions")

h.describe("mentions", function()
  h.it("find_mentions extracts a codebase mention", function()
    local m = Mentions.find_mentions("fix the @codebase auth middleware bug")
    h.equals(1, #m)
    h.equals("codebase", m[1].type)
    h.equals("auth middleware bug", m[1].arg)
  end)

  h.it("find_mentions stops at the next @type or newline", function()
    local m = Mentions.find_mentions("@docs README.md\nand @web ollama setup")
    h.equals(2, #m)
    h.equals("docs", m[1].type)
    h.equals("README.md", m[1].arg)
    h.equals("web", m[2].type)
    h.equals("ollama setup", m[2].arg)
  end)

  h.it("find_mentions returns empty for no mentions", function()
    h.equals(0, #Mentions.find_mentions("plain prompt with no mentions"))
  end)

  h.it("find_mentions records the literal token span for replacement", function()
    local m = Mentions.find_mentions("@git pr 123")
    h.equals(1, #m)
    h.equals("git", m[1].type)
    h.equals("pr 123", m[1].arg)
    h.equals("@git pr 123", m[1].token)
  end)

  h.it("find_mentions recognizes file, folder, and symbol types", function()
    local m = Mentions.find_mentions("@file src/main.go\n@folder lib\n@symbol authenticate")
    h.equals(3, #m)
    h.equals("file", m[1].type)
    h.equals("src/main.go", m[1].arg)
    h.equals("folder", m[2].type)
    h.equals("lib", m[2].arg)
    h.equals("symbol", m[3].type)
    h.equals("authenticate", m[3].arg)
  end)
end)
